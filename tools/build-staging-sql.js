#!/usr/bin/env node
/* Joins the database files into one script to paste into a fresh staging project, in the order
   they have to run, with the production project reference swapped for staging's.

   Catalog dumps and the production data fixes are left out on purpose: staging gets its catalog
   by importing staging-store.json through the admin, which is the same path a restore uses.

   Run:  node tools/build-staging-sql.js          (writes staging-bootstrap.sql next to it) */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PROD_REF = 'soydgxrrwozmiqzutypr';

/* Order matters: later files alter what earlier ones create. */
const FILES = [
  ['supabase-setup.sql', 'Tables, row-level security, and the public RPC functions'],
  ['supabase/stock-and-analytics-2026-09-22.sql', 'Stock table and first-party analytics'],
  ['supabase/timed-sale-2026-09-22.sql', 'Timed sale, priced by the database as well as the shop'],
  ['supabase/reviews.sql', 'Reviews: tables, photo bucket, and the verified-buyer checks'],
  ['supabase/gift-orders.sql', 'Gift flag on an order, and the packing slip without prices'],
  ['supabase/release-orders-cron.sql', 'Scheduled: hand paid orders to ShipStation (needs the Edge Function)'],
  ['supabase/review-invites-cron.sql', 'Scheduled: ask for a review a week after delivery (needs the Edge Function)']
];

function main() {
  const ref = String(process.argv[2] || '').trim() || readRef();
  if (!/^[a-z0-9-]{10,}$/.test(ref)) {
    console.error('\nNo staging project reference. Set "supabaseUrl" in staging.config.json, or pass the ref:\n  node tools/build-staging-sql.js abcdefghijklmnop\n');
    process.exit(1);
  }
  if (ref === PROD_REF) { console.error('\nThat is the production reference. Staging needs its own project.\n'); process.exit(1); }

  const out = [
    '-- =====================================================================',
    '-- Home Weavers — STAGING database bootstrap',
    '-- Generated by tools/build-staging-sql.js on ' + new Date().toISOString().slice(0, 10) + '.',
    '-- Target project: ' + ref,
    '--',
    '-- Paste the whole file into the STAGING project’s SQL Editor and run it.',
    '-- Then run supabase/staging-seed.sql for sample orders, messages and stock.',
    '-- ====================================================================='
  ];
  let swaps = 0;
  for (const [rel, what] of FILES) {
    const full = path.join(ROOT, rel);
    if (!fs.existsSync(full)) { console.error('Missing: ' + rel); process.exit(1); }
    let sql = fs.readFileSync(full, 'utf8');
    const before = sql;
    sql = sql.split(PROD_REF).join(ref);
    if (sql !== before) swaps++;
    out.push('', '', '-- #####################################################################',
      '-- ' + rel, '-- ' + what, '-- #####################################################################', '', sql.replace(/\s+$/, ''));
  }
  const dest = path.join(ROOT, 'staging-bootstrap.sql');
  fs.writeFileSync(dest, out.join('\n') + '\n');
  console.log('Wrote ' + dest);
  console.log('  ' + FILES.length + ' files, ' + out.join('\n').split('\n').length + ' lines, project reference swapped in ' + swaps + ' of them.');
  if (fs.readFileSync(dest, 'utf8').indexOf(PROD_REF) >= 0) {
    console.error('\nSTOP: the production reference is still in the output. Do not run this file.\n');
    process.exit(1);
  }
}

function readRef() {
  const f = path.join(ROOT, 'staging.config.json');
  if (!fs.existsSync(f)) return '';
  try {
    const m = String(JSON.parse(fs.readFileSync(f, 'utf8')).supabaseUrl || '').match(/https:\/\/([a-z0-9-]+)\.supabase\.co/);
    return m ? m[1] : '';
  } catch (e) { return ''; }
}

main();
